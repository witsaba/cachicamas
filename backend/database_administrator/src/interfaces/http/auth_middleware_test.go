func TestIdentityFromCookie_NeverEmitsSetCookie(t *testing.T) {
	// S-BAM-030: the verifier is a STATELESS reader. It MUST NOT
	// emit Set-Cookie headers under any code path (success, missing
	// cookie, tampered cookie, repo error).
	cases := []struct {
		name     string
		cookieV  string
		authSec  string
		repoErr  error
		wantCode int
	}{
		{"valid", loadFixtureJWE(t), fixtureAuthSecret, nil, http.StatusOK},
		{"tampered", loadFixtureJWE(t), "wrong-secret-thirty-two-bytes-aaaaaa", nil, http.StatusUnauthorized},
		{"missing", "", fixtureAuthSecret, nil, http.StatusUnauthorized},
		{"repo_error", loadFixtureJWE(t), fixtureAuthSecret, errors.New("db down"), http.StatusUnauthorized},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			repo := newFakeIdentityRepo()
			repo.lookupErr = tc.repoErr
			logger, _ := newCapturingLogger()
			_, tp := newSpanRecorder()
			t.Cleanup(func() { _ = tp.Shutdown(context.Background()) })

			e := newRouterWithAuth(IdentityMiddlewareConfig{
				AuthSecret:     tc.authSec,
				CookieName:     fixtureCookieName,
				IdentityRepo:   repo,
				Logger:         logger,
				TracerProvider: tp,
			})

			req := newRequestWithCookie(t, tc.cookieV)
			rec2 := httptest.NewRecorder()
			e.ServeHTTP(rec2, req)

			if rec2.Code != tc.wantCode {
				t.Errorf("expected %d, got %d body=%q", tc.wantCode, rec2.Code, rec2.Body.String())
			}
			for k, vs := range rec2.Header() {
				if strings.EqualFold(k, "Set-Cookie") {
					t.Errorf("verifier MUST NOT emit Set-Cookie, got %v=%v", k, vs)
				}
			}
		})
	}
}

