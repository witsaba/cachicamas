const (
	// fixtureAuthSecret is the AUTH_SECRET used by the regenerate
	// script to produce the fixture JWE. Must match the script.
	fixtureAuthSecret = "test-secret-do-not-use-in-prod-thirtytwo-bytes!"
	// fixtureCookieName matches what Auth.js for Qwik emits when
	// AUTH_URL is http://localhost (insecure). Production uses
	// __Secure-authjs.session-token — exercised in a separate test.
	fixtureCookieName = "authjs.session-token"
	// fixtureExpectedEmail is the email claim inside the fixture JWE.
	// The IdentityRepository fake matches against this value.
	fixtureExpectedEmail = "octocat@example.com"
)

// loadFixtureJWE returns the committed fixture JWE from testdata. If
// the fixture is missing the test fails — the regenerate script must
// be run to produce it. The fixture file starts with a header comment
// (lines starting with #) followed by the JWE on its own line; we
// extract only the JWE line so the cookie parser doesn't choke on
// the leading comment text.
func loadFixtureJWE(t *testing.T) string {
	t.Helper()
	data, err := os.ReadFile("testdata/authjs_session_token.jwe")
	if err != nil {
		t.Fatalf("fixture missing: %v — run scripts/regenerate_authjs_testdata.sh", err)
	}
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		return line
	}
	t.Fatalf("fixture file has no JWE content (only header comments?)")
	return ""
}

// fakeIdentityRepo is the in-memory IdentityRepository used by these
// tests.
type fakeIdentityRepo struct {
	mu                 sync.Mutex
	byEmail            map[string]*domain.Identity
	lookupErr          error
	byProviderCalls    int
	byEmailCalls       int
	lastProviderCall   string
	lastProviderIDCall string
	lastEmailCall      string
}

func newFakeIdentityRepo() *fakeIdentityRepo {
	return &fakeIdentityRepo{
		byEmail: map[string]*domain.Identity{
			fixtureExpectedEmail: {
				ID:                42,
				Email:             fixtureExpectedEmail,
				Name:              "Octocat",
				ImageURL:          "https://github.com/avatars/octo.png",
				Provider:          "github",
				ProviderAccountID: "12345",
			},
		},
	}
}

func (r *fakeIdentityRepo) LookupByProviderAccountID(_ context.Context, provider, providerAccountID string) (*domain.Identity, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.byProviderCalls++
	r.lastProviderCall = provider
	r.lastProviderIDCall = providerAccountID
	if r.lookupErr != nil {
		return nil, r.lookupErr
	}
	for _, id := range r.byEmail {
		if id.Provider == provider && id.ProviderAccountID == providerAccountID {
			dup := *id
			return &dup, nil
		}
	}
	return nil, &domain.IdentityNotFoundError{Email: provider + "/" + providerAccountID}
}

func (r *fakeIdentityRepo) LookupByEmail(_ context.Context, email string) (*domain.Identity, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.byEmailCalls++
	r.lastEmailCall = email
	if r.lookupErr != nil {
		return nil, r.lookupErr
	}
	id, ok := r.byEmail[strings.ToLower(email)]
	if !ok {
		return nil, &domain.IdentityNotFoundError{Email: email}
	}
	return id, nil
}

func (r *fakeIdentityRepo) Upsert(_ context.Context, ev domain.IdentityEvent) (*domain.Identity, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.byProviderCalls++
	r.lastProviderCall = ev.Provider
	r.lastProviderIDCall = ev.ProviderAccountID
	if r.lookupErr != nil {
		return nil, r.lookupErr
	}
	for _, id := range r.byEmail {
		if id.Provider == ev.Provider && id.ProviderAccountID == ev.ProviderAccountID {
			dup := *id
			return &dup, nil
		}
	}
	return &domain.Identity{
		ID:                int64(len(r.byEmail) + 1),
		Email:             ev.Email,
		Name:              ev.Name,
		ImageURL:          ev.ImageURL,
		Provider:          ev.Provider,
		ProviderAccountID: ev.ProviderAccountID,
	}, nil
}

// newCapturingLogger returns an slog.Logger whose output is captured
// into a buffer the test can inspect.
func newCapturingLogger() (*slog.Logger, *bytes.Buffer) {
	buf := &bytes.Buffer{}
	return slog.New(slog.NewJSONHandler(buf, &slog.HandlerOptions{Level: slog.LevelDebug})), buf
}

// newSpanRecorder sets up an OTel span recorder so tests can assert
// that the middleware emits a span per request.
func newSpanRecorder() (*tracetest.SpanRecorder, *sdktrace.TracerProvider) {
	rec := tracetest.NewSpanRecorder()
	tp := sdktrace.NewTracerProvider(sdktrace.WithSpanProcessor(rec))
	return rec, tp
}

// newRouterWithAuth builds a tiny Echo router that mounts a single
// protected route /api/v1/protected/whoami behind the
// IdentityFromCookie middleware. The handler echoes the identity
// name it observed (or "NO_IDENTITY" if the middleware did not set
// one) and the HTTP status 200, so tests can assert both the
// identity propagation and the response.
func newRouterWithAuth(cfg IdentityMiddlewareConfig) *echo.Echo {
	e := echo.New()
	e.Use(func(next echo.HandlerFunc) echo.HandlerFunc {
		return func(c *echo.Context) error {
			ctx, span := sdktrace.NewTracerProvider().Tracer("test").Start(context.Background(), "noop")
			_ = ctx
			_ = span
			return next(c)
		}
	})
	mw := IdentityFromCookie(cfg)
	e.GET("/api/v1/protected/whoami", mw(func(c *echo.Context) error {
		v := c.Get(IdentityContextKey)
		if v == nil {
			return c.NoContent(http.StatusOK)
		}
		id, ok := v.(*domain.Identity)
		if !ok {
			return fmt.Errorf("identity has wrong type: %T", v)
		}
		c.Response().Header().Set("Content-Type", "application/json")
		return json.NewEncoder(c.Response()).Encode(map[string]any{
			"id":     id.ID,
			"email":  id.Email,
			"name":   id.Name,
			"provider": id.Provider,
		})
	}))
	return e
}

// newRequestWithCookie builds an httptest request carrying the
// authjs.session-token cookie with the given raw JWE value.
func newRequestWithCookie(t *testing.T, cookieValue string) *http.Request {
	t.Helper()
	req := httptest.NewRequest(http.MethodGet, "/api/v1/protected/whoami", nil)
	if cookieValue != "" {
		req.AddCookie(&http.Cookie{
			Name:  fixtureCookieName,
			Value: cookieValue,
		})
	}
	return req
}

