func TestIdentityFromCookie_ValidCookie_PopulatesIdentity(t *testing.T) {
	// S-BAM-010: a request whose cookie carries a JWE signed by the
	// project's AUTH_SECRET + a payload whose email matches an
	// identity.user row -> middleware calls next(c) without writing
	// any response, and the downstream handler observes a non-nil
	// *Identity in c.Get("identity") with Email == payload.email.
	jweValue := loadFixtureJWE(t)
	repo := newFakeIdentityRepo()
	logger, _ := newCapturingLogger()
	rec, tp := newSpanRecorder()
	t.Cleanup(func() { _ = tp.Shutdown(context.Background()) })

	e := newRouterWithAuth(IdentityMiddlewareConfig{
		AuthSecret:     fixtureAuthSecret,
		CookieName:     fixtureCookieName,
		IdentityRepo:   repo,
		Logger:         logger,
		TracerProvider: tp,
	})

	req := newRequestWithCookie(t, jweValue)
	rec2 := httptest.NewRecorder()
	e.ServeHTTP(rec2, req)

	if rec2.Code != http.StatusOK {
		t.Fatalf("expected 200, got %d body=%q", rec2.Code, rec2.Body.String())
	}
	var body map[string]any
	if err := json.Unmarshal(rec2.Body.Bytes(), &body); err != nil {
		t.Fatalf("response body is not JSON: %v body=%q", err, rec2.Body.String())
	}
	if body["email"] != fixtureExpectedEmail {
		t.Errorf("expected email %q in handler response, got %v", fixtureExpectedEmail, body["email"])
	}
	// OTel span emitted (S-BAM-070).
	if len(rec.Ended()) == 0 {
		t.Error("expected OTel span to be emitted, none found")
	}
}

