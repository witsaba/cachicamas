func TestIdentityFromCookie_EmitsSlogAndSpan(t *testing.T) {
	// S-BAM-070 + S-BAM-072: a successful request emits a slog line
	// with the email HASHED (not raw). The hash is sha256(email)
	// truncated to 12 hex chars. The slog JSON handler emits fields
	// as `"key":"value"` so we match against that shape.
	jweValue := loadFixtureJWE(t)
	repo := newFakeIdentityRepo()
	logger, logBuf := newCapturingLogger()
	_, tp := newSpanRecorder()
	t.Cleanup(func() { _ = tp.Shutdown(context.Background()) })

	e := newRouterWithAuth(IdentityMiddlewareConfig{
		AuthSecret:     fixtureAuthSecret,
		CookieName:     fixtureCookieName,
		IdentityRepo:   repo,
		Logger:         logger,
		TracerProvider: tp,
	})

	req := newRequestWithCookie(t, jweValue)
	rec2 := httptest.NewRecorder()
	e.ServeHTTP(rec2, req)

	logs := logBuf.String()
	if !strings.Contains(logs, `"msg":"auth.verify"`) {
		t.Errorf("expected slog line with msg=auth.verify, got %q", logs)
	}
	if strings.Contains(logs, fixtureExpectedEmail) {
		t.Errorf("PII leaked: raw email in logs: %q", logs)
	}
	h := sha256.Sum256([]byte(fixtureExpectedEmail))
	wantHash := hex.EncodeToString(h[:])[:12]
	wantKey := `"email_hash":"` + wantHash + `"`
	if !strings.Contains(logs, wantKey) {
		t.Errorf("expected log line to contain %q, got %q", wantKey, logs)
	}
}

