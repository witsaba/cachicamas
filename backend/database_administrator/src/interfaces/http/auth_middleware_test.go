// Package httpiface_test contains the test suite for the IdentityFromCookie
// middleware introduced by cachicamas-github-login PR-3.
//
// Reference: openspec/changes/cachicamas-github-login/specs/backend-auth-middleware/spec.md
//
//   R-BAM-001 (S-BAM-010..S-BAM-012) — the middleware reads the JWE cookie,
//   decrypts it with AUTH_SECRET, looks up the identity, populates
//   c.Set("identity", *Identity), and returns 401 on any failure.
//   R-BAM-002 (S-BAM-020) — decryption uses lestrrat-go/jwx/v2.
//   R-BAM-003 (S-BAM-030) — middleware never emits a Set-Cookie header.
//   R-BAM-021 (S-BAM-070..S-BAM-072) — OTel span + slog line per request,
//   PII (email) is sha256(first 12 hex chars), not raw.
//   R-BAM-030 (S-BAM-080..S-BAM-081) — AUTH_SECRET must be set AND at least
//   32 raw bytes; otherwise startup crashes.
//   R-BAM-100 (S-BAM-110) — all tests pass under -race.
//
// The fixture JWE (testdata/authjs_session_token.jwe) is generated by
// `scripts/regenerate_authjs_testdata.sh`, which runs the @auth/core
// encoder against a known payload using a known AUTH_SECRET. The Go
// tests read both the JWE and the expected plaintext JSON and assert
// byte-equality. This is the load-bearing TDD evidence for the
// envelope contract documented in design §3.
